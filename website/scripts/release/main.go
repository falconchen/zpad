//go:build ignore

// Command release turns a GitHub release into the site's data/release.json.
//
//	go run website/scripts/release/main.go /tmp/release.json website/data/release.json
//
// The input is the JSON of GET /repos/{owner}/{repo}/releases/tags/{tag}, which
// .github/workflows/website.yml writes with `gh api`. The output drives the
// download page, the release notes on the home page and the _redirects file.
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"regexp"
	"strings"
	"time"
)

type asset struct {
	Name  string `json:"name"`
	URL   string `json:"url"`
	Size  string `json:"size"`
	Bytes int64  `json:"bytes"`
}

type release struct {
	Tag         string           `json:"tag"`
	Version     string           `json:"version"`
	PublishedAt string           `json:"published_at"`
	Date        string           `json:"date"`
	URL         string           `json:"url"`
	Notes       string           `json:"notes"`
	Assets      map[string]asset `json:"assets"`
}

type github struct {
	TagName     string    `json:"tag_name"`
	Name        string    `json:"name"`
	Body        string    `json:"body"`
	HTMLURL     string    `json:"html_url"`
	Draft       bool      `json:"draft"`
	Prerelease  bool      `json:"prerelease"`
	PublishedAt time.Time `json:"published_at"`
	Assets      []struct {
		Name string `json:"name"`
		Size int64  `json:"size"`
		URL  string `json:"browser_download_url"`
	} `json:"assets"`
}

// The file names mygo build produces. The deltas and update manifests are for
// the app's updater, not for people downloading by hand.
var wanted = []struct {
	key   string
	label string
	match *regexp.Regexp
}{
	{"macos_arm64", "macOS Apple Silicon", regexp.MustCompile(`^zpad-.*-arm64\.dmg$`)},
	{"macos_amd64", "macOS Intel", regexp.MustCompile(`^zpad-.*-amd64\.dmg$`)},
	{"windows_setup", "Windows installer", regexp.MustCompile(`^zpad-setup-.*-amd64\.exe$`)},
	{"windows_portable", "Windows portable", regexp.MustCompile(`-windows-amd64-portable\.zip$`)},
	{"checksums", "checksums", regexp.MustCompile(`^SHA256SUMS$`)},
}

func main() {
	if len(os.Args) < 3 || len(os.Args) > 4 {
		fail("usage: go run website/scripts/release/main.go <release.json> <out.json> [_redirects]")
	}
	in, err := os.ReadFile(os.Args[1])
	if err != nil {
		fail(err.Error())
	}

	var gh github
	if err := json.Unmarshal(in, &gh); err != nil {
		fail(fmt.Sprintf("%s: %v", os.Args[1], err))
	}
	if gh.Draft || gh.Prerelease {
		// A draft or a pre-release must not point the site's download buttons at
		// something the updater will not offer.
		fmt.Fprintf(os.Stderr, "skip %s: draft=%v prerelease=%v\n", gh.TagName, gh.Draft, gh.Prerelease)
		return
	}
	if gh.TagName == "" || len(gh.Assets) == 0 {
		fail(fmt.Sprintf("%s: no tag or no assets", os.Args[1]))
	}

	out := release{
		Tag:         gh.TagName,
		Version:     strings.TrimPrefix(gh.TagName, "v"),
		PublishedAt: gh.PublishedAt.UTC().Format(time.RFC3339),
		Date:        gh.PublishedAt.UTC().Format("2006-01-02"),
		URL:         gh.HTMLURL,
		Notes:       strings.TrimSpace(gh.Body),
		Assets:      map[string]asset{},
	}

	for _, want := range wanted {
		found := false
		for _, a := range gh.Assets {
			if !want.match.MatchString(a.Name) {
				continue
			}
			out.Assets[want.key] = asset{
				Name:  a.Name,
				URL:   a.URL,
				Size:  humanSize(a.Size),
				Bytes: a.Size,
			}
			found = true
			break
		}
		if !found {
			fmt.Fprintf(os.Stderr, "warning: %s: no asset matches %s\n", want.key, want.label)
		}
	}
	if len(out.Assets) == 0 {
		fail("no known asset found; is this a ZPad release?")
	}

	encoded, err := json.MarshalIndent(out, "", "  ")
	if err != nil {
		fail(err.Error())
	}
	if err := os.WriteFile(os.Args[2], append(encoded, '\n'), 0o644); err != nil {
		fail(err.Error())
	}
	if len(os.Args) == 4 {
		if err := writeRedirects(os.Args[3], out); err != nil {
			fail(err.Error())
		}
	}
	fmt.Printf("%s: %s, %d assets\n", os.Args[2], out.Tag, len(out.Assets))
}

// writeRedirects gives the site stable download URLs: /download/mac-arm64
// always points at the newest build, whatever it is called.
func writeRedirects(path string, r release) error {
	aliases := []struct{ alias, key string }{
		{"/download/mac-arm64", "macos_arm64"},
		{"/download/mac-intel", "macos_amd64"},
		{"/download/windows", "windows_setup"},
		{"/download/windows-portable", "windows_portable"},
	}
	var b strings.Builder
	b.WriteString("# Generated by website/scripts/release from data/release.json.\n")
	b.WriteString("# Cloudflare Pages reads this file from the deployment root.\n")
	for _, a := range aliases {
		asset, ok := r.Assets[a.key]
		if !ok {
			continue
		}
		fmt.Fprintf(&b, "%s  %s  302\n", a.alias, asset.URL)
	}
	return os.WriteFile(path, []byte(b.String()), 0o644)
}

func humanSize(n int64) string {
	const mb = 1024 * 1024
	if n >= mb {
		return fmt.Sprintf("%.1f MB", float64(n)/mb)
	}
	return fmt.Sprintf("%.0f KB", float64(n)/1024)
}

func fail(msg string) {
	fmt.Fprintln(os.Stderr, msg)
	os.Exit(1)
}
